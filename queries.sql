-- ============================================
--   ANALYTICAL QUERIES FOR HOSPITAL DATABASE
-- ============================================

------------------------------------------------
-- 1. List all patients
------------------------------------------------
SELECT * FROM Patients;

------------------------------------------------
-- 2. Count how many patients each doctor has seen
------------------------------------------------
SELECT 
    d.doctor_id,
    d.name AS doctor_name,
    COUNT(v.visit_id) AS total_visits
FROM Doctors d
LEFT JOIN Visits v ON d.doctor_id = v.doctor_id
GROUP BY d.doctor_id, d.name
ORDER BY total_visits DESC;

------------------------------------------------
-- 3. Total revenue generated by each doctor
------------------------------------------------
SELECT 
    d.doctor_id,
    d.name AS doctor_name,
    SUM(v.cost) AS total_revenue
FROM Doctors d
JOIN Visits v ON d.doctor_id = v.doctor_id
GROUP BY d.doctor_id, d.name
ORDER BY total_revenue DESC;

------------------------------------------------
-- 4. Most common diagnosis
------------------------------------------------
SELECT 
    diagnosis,
    COUNT(*) AS frequency
FROM Visits
GROUP BY diagnosis
ORDER BY frequency DESC;

------------------------------------------------
-- 5. Average visit cost per medical specialty
------------------------------------------------
SELECT 
    d.specialty,
    AVG(v.cost) AS avg_cost
FROM Doctors d
JOIN Visits v ON d.doctor_id = v.doctor_id
GROUP BY d.specialty
ORDER BY avg_cost DESC;

------------------------------------------------
-- 6. Patients with more than 2 visits
------------------------------------------------
SELECT 
    p.patient_id,
    p.name,
    COUNT(v.visit_id) AS visit_count
FROM Patients p
JOIN Visits v ON p.patient_id = v.patient_id
GROUP BY p.patient_id, p.name
HAVING COUNT(v.visit_id) > 2
ORDER BY visit_count DESC;

------------------------------------------------
-- 7. First visit date for each patient
------------------------------------------------
SELECT 
    p.patient_id,
    p.name,
    MIN(v.visit_date) AS first_visit
FROM Patients p
JOIN Visits v ON p.patient_id = v.patient_id
GROUP BY p.patient_id, p.name
ORDER BY first_visit;

------------------------------------------------
-- 8. Medication usage frequency
------------------------------------------------
SELECT 
    m.name AS medication,
    COUNT(pres.prescription_id) AS times_prescribed
FROM Medications m
JOIN Prescriptions pres ON m.medication_id = pres.medication_id
GROUP BY m.name
ORDER BY times_prescribed DESC;

------------------------------------------------
-- 9. Visits with prescriptions (joined across 3 tables)
------------------------------------------------
SELECT 
    v.visit_id,
    p.name AS patient_name,
    d.name AS doctor_name,
    m.name AS medication,
    pres.dosage,
    v.diagnosis,
    v.visit_date
FROM Visits v
JOIN Patients p ON v.patient_id = p.patient_id
JOIN Doctors d ON v.doctor_id = d.doctor_id
JOIN Prescriptions pres ON v.visit_id = pres.visit_id
JOIN Medications m ON pres.medication_id = m.medication_id
ORDER BY v.visit_date;

------------------------------------------------
-- 10. Total cost per patient (lifetime medical cost)
------------------------------------------------
SELECT 
    p.patient_id,
    p.name,
    SUM(v.cost) AS lifetime_cost
FROM Patients p
JOIN Visits v ON p.patient_id = v.patient_id
GROUP BY p.patient_id, p.name
ORDER BY lifetime_cost DESC;

------------------------------------------------
-- 11. Rank doctors by revenue (window function)
------------------------------------------------
SELECT 
    d.doctor_id,
    d.name AS doctor_name,
    SUM(v.cost) AS total_revenue,
    RANK() OVER (ORDER BY SUM(v.cost) DESC) AS revenue_rank
FROM Doctors d
JOIN Visits v ON d.doctor_id = v.doctor_id
GROUP BY d.doctor_id, d.name;

------------------------------------------------
-- 12. Monthly visit count (trend analysis)
------------------------------------------------
SELECT 
    DATE_TRUNC('month', visit_date) AS month,
    COUNT(*) AS total_visits
FROM Visits
GROUP BY month
ORDER BY month;

------------------------------------------------
-- 13. Most expensive visit per patient
------------------------------------------------
SELECT 
    p.patient_id,
    p.name,
    MAX(v.cost) AS highest_cost
FROM Patients p
JOIN Visits v ON p.patient_id = v.patient_id
GROUP BY p.patient_id, p.name
ORDER BY highest_cost DESC;

------------------------------------------------
-- 14. Doctors who prescribed the most medications
------------------------------------------------
SELECT 
    d.doctor_id,
    d.name AS doctor_name,
    COUNT(pres.prescription_id) AS total_prescriptions
FROM Doctors d
JOIN Visits v ON d.doctor_id = v.doctor_id
JOIN Prescriptions pres ON v.visit_id = pres.visit_id
GROUP BY d.doctor_id, d.name
ORDER BY total_prescriptions DESC;

------------------------------------------------
-- 15. Patients diagnosed with anxiety (example filter)
------------------------------------------------
SELECT 
    p.patient_id,
    p.name,
    v.visit_date,
    v.cost
FROM Patients p
JOIN Visits v ON p.patient_id = v.patient_id
WHERE v.diagnosis ILIKE '%anxiety%'
ORDER BY v.visit_date;

------------------------------------------------
-- 16. Average cost per diagnosis
------------------------------------------------
SELECT 
    diagnosis,
    AVG(cost) AS avg_cost
FROM Visits
GROUP BY diagnosis
ORDER BY avg_cost DESC;

------------------------------------------------
-- 17. Number of medications prescribed per visit
------------------------------------------------
SELECT 
    v.visit_id,
    COUNT(pres.prescription_id) AS medication_count
FROM Visits v
LEFT JOIN Prescriptions pres ON v.visit_id = pres.visit_id
GROUP BY v.visit_id
ORDER BY medication_count DESC;

------------------------------------------------
-- 18. Patients who have never been prescribed medication
------------------------------------------------
SELECT 
    p.patient_id,
    p.name
FROM Patients p
LEFT JOIN Visits v ON p.patient_id = v.patient_id
LEFT JOIN Prescriptions pres ON v.visit_id = pres.visit_id
WHERE pres.prescription_id IS NULL;

------------------------------------------------
-- 19. Doctor specialty performance (total visits)
------------------------------------------------
SELECT 
    d.specialty,
    COUNT(v.visit_id) AS total_visits
FROM Doctors d
JOIN Visits v ON d.doctor_id = v.doctor_id
GROUP BY d.specialty
ORDER BY total_visits DESC;

------------------------------------------------
-- 20. Most prescribed medication per diagnosis
------------------------------------------------
SELECT 
    v.diagnosis,
    m.name AS medication,
    COUNT(*) AS times_used
FROM Visits v
JOIN Prescriptions pres ON v.visit_id = pres.visit_id
JOIN Medications m ON pres.medication_id = m.medication_id
GROUP BY v.diagnosis, m.name
ORDER BY v.diagnosis, times_used DESC;
